"""Writes the generated tables of the library.

From the generated files of the Go port (which are written from the .NET sources):
  include/fasthtmlparser/tag.hpp   known tag names (Tag::DIV, ...)
  include/fasthtmlparser/attr.hpp  common attribute names (attr::HREF, ...)
  src/entities.inc                 HTML5 named character references

From the Unicode database of the Python that runs it:
  src/unicode_tables.inc           simple and full case mappings, White_Space, letters and digits

    python tools/gen.py ../fasthtmlparser
"""

import re
import sys
import unicodedata
from pathlib import Path

HEADER = "// Code generated by tools/gen.py; DO NOT EDIT.\n"


def go_string(literal: str) -> str:
    """Decodes a Go interpreted string literal (without the quotes)."""
    out = []
    i = 0
    while i < len(literal):
        c = literal[i]
        if c != "\\":
            out.append(c)
            i += 1
            continue
        e = literal[i + 1]
        if e == "u":
            out.append(chr(int(literal[i + 2 : i + 6], 16)))
            i += 6
        elif e == "U":
            out.append(chr(int(literal[i + 2 : i + 10], 16)))
            i += 10
        elif e == "x":
            out.append(chr(int(literal[i + 2 : i + 4], 16)))
            i += 4
        else:
            out.append({"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "'": "'"}[e])
            i += 2
    return "".join(out)


def cpp_string(s: str) -> str:
    """A C++ narrow string literal holding the UTF-8 bytes of s (octal escapes: they never run into the next char)."""
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '"\\':
            out.append("\\" + c)
        elif 0x20 <= b < 0x7F and c != "?":  # '?' avoids trigraphs
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def upper_snake(camel: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", camel).upper()


def tags(go: Path) -> str:
    text = (go / "names_gen.go").read_text(encoding="utf-8")
    consts = re.findall(r"^\tTag(\w+)(?: Tag = iota)?$", text, re.M)
    names = [go_string(s) for s in re.findall(r'^\t"((?:[^"\\]|\\.)*)",$', text[text.index("var tagNames") :], re.M)]
    assert len(consts) == len(names), (len(consts), len(names))
    b = [HEADER, "#pragma once\n\n#include <compare>\n#include <cstddef>\n#include <cstdint>\n#include <optional>\n"]
    b.append("#include <string_view>\n\nnamespace fasthtmlparser {\n\nnamespace detail {\n")
    b.append(f"inline constexpr std::size_t tag_count = {len(names)};\n\n")
    b.append("/// The lower-case tag names, indexed by Tag.\n")
    b.append("inline constexpr std::string_view tag_names[tag_count] = {\n")
    for n in names:
        b.append(f"    {cpp_string(n)},\n")
    b.append("};\n} // namespace detail\n\n")
    b.append("/// A known tag name: HTML (incl. obsolete), SVG, MathML and common XML (RSS, Atom, sitemap), as Tag::DIV.\n")
    b.append("/// Names that are not in the list are matched as strings (by_name(\"my-widget\")).\n")
    b.append("class Tag {\npublic:\n")
    b.append("    constexpr explicit Tag(std::uint16_t index) noexcept : index_(index) {}\n\n")
    b.append("    /// The index of the tag in the list of known tags.\n")
    b.append("    constexpr std::uint16_t index() const noexcept { return index_; }\n\n")
    b.append("    /// The lower-case name (\"div\", \"!--\" for comments).\n")
    b.append("    constexpr std::string_view name() const noexcept { return detail::tag_names[index_]; }\n\n")
    b.append("    /// The tag with this name (ASCII case-insensitive), if it is a known one.\n")
    b.append("    static std::optional<Tag> from_name(std::string_view name) noexcept;\n\n")
    b.append("    friend constexpr bool operator==(Tag, Tag) noexcept = default;\n")
    b.append("    friend constexpr auto operator<=>(Tag, Tag) noexcept = default;\n\n")
    for c, n in zip(consts, names):
        b.append(f"    static const Tag {upper_snake(c)}; ///< {n}\n")
    b.append("\nprivate:\n    std::uint16_t index_;\n};\n\n")
    for i, c in enumerate(consts):
        b.append(f"inline constexpr Tag Tag::{upper_snake(c)}{{{i}}};\n")
    b.append("\n} // namespace fasthtmlparser\n")
    return "".join(b)


def attributes(go: Path) -> str:
    text = (go / "attributes_gen.go").read_text(encoding="utf-8")
    pairs = re.findall(r'^\tAttr(\w+)\s*=\s*"((?:[^"\\]|\\.)*)"$', text, re.M)
    b = [HEADER, "#pragma once\n\n#include <string_view>\n\n"]
    b.append("/// Common HTML / SVG / XML attribute names, for attr(), attr_raw(), Query::attr() and the shortcuts.\n")
    b.append("/// Any other name works as a plain string.\nnamespace fasthtmlparser::attr {\n\n")
    for c, v in pairs:
        b.append(f"inline constexpr std::string_view {upper_snake(c)} = {cpp_string(go_string(v))};\n")
    b.append("\n} // namespace fasthtmlparser::attr\n")
    return "".join(b)


def entities(go: Path) -> str:
    text = (go / "entities_gen.go").read_text(encoding="utf-8")
    rows = re.findall(r'^\t"(\w+)":\s*\{"((?:[^"\\]|\\.)*)", (true|false)\},$', text, re.M)
    max_name = int(re.search(r"entityMaxName\s*=\s*(\d+)", text).group(1))
    max_legacy = int(re.search(r"entityMaxLegacyName\s*=\s*(\d+)", text).group(1))
    rows.sort(key=lambda r: r[0].encode())
    b = [HEADER]
    b.append("// HTML5 named character references (without '&' and ';'), sorted by name; legacy ones are also\n")
    b.append("// recognized without ';'. Included by src/decode.cpp.\n\n")
    b.append(f"inline constexpr std::size_t entity_max_name = {max_name};\n")
    b.append(f"inline constexpr std::size_t entity_max_legacy_name = {max_legacy};\n\n")
    b.append(f"inline constexpr Entity entities[{len(rows)}] = {{\n")
    for name, value, legacy in rows:
        b.append(f"    {{{cpp_string(name)}, {cpp_string(go_string(value))}, {legacy}}},\n")
    b.append("};\n")
    return "".join(b)


def ranges(pred) -> list:
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def case_table(name: str, convert) -> list:
    """Simple mappings as (from, to); a full mapping to several chars as (from, 0x80000000 | pool index)."""
    rows, pool = [], []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        m = convert(c)
        if m == c:
            continue
        if len(m) == 1:
            rows.append((cp, ord(m)))
        else:
            rows.append((cp, 0x80000000 | len(pool)))
            pool.append(m)
    return rows, pool


def unicode_tables() -> str:
    b = [HEADER, f"// Unicode {unicodedata.unidata_version}. Included by src/chars.cpp.\n\n"]

    def lower_one(c):  # one char at a time: the final-sigma rule is applied by the caller
        return "σ" if c == "Σ" else c.lower()

    for name, convert in (("lower", lower_one), ("upper", str.upper)):
        rows, pool = case_table(name, convert)
        b.append(f"inline constexpr CaseRow {name}_map[{len(rows)}] = {{\n")
        for i in range(0, len(rows), 6):
            b.append("    " + " ".join(f"{{0x{a:X}, 0x{t:X}}}," for a, t in rows[i : i + 6]) + "\n")
        b.append("};\n")
        b.append(f"inline constexpr std::string_view {name}_pool[{max(len(pool), 1)}] = {{\n")
        for m in pool or [""]:
            b.append(f"    {cpp_string(m)},\n")
        b.append("};\n\n")

    def emit_ranges(name, rs):
        b.append(f"inline constexpr Range {name}[{len(rs)}] = {{\n")
        for i in range(0, len(rs), 6):
            b.append("    " + " ".join(f"{{0x{a:X}, 0x{z:X}}}," for a, z in rs[i : i + 6]) + "\n")
        b.append("};\n\n")

    cat = unicodedata.category
    # Alphabetic, approximated by the general category: letters, letter numbers and marks (Other_Alphabetic is mostly
    # combining marks); Numeric: the N* categories. Only used for XPath names.
    emit_ranges("alphabetic_ranges", ranges(lambda cp: cat(chr(cp))[0] == "L" or cat(chr(cp)) in ("Nl", "Mn", "Mc")))
    emit_ranges("numeric_ranges", ranges(lambda cp: cat(chr(cp)) in ("Nd", "Nl", "No")))
    # Cased letters and case-ignorable chars, for the final-sigma rule of lower-casing.
    emit_ranges("cased_ranges", ranges(lambda cp: chr(cp).lower() != chr(cp).upper() or cat(chr(cp)) in ("Lt",)))
    emit_ranges(
        "case_ignorable_ranges",
        ranges(lambda cp: cat(chr(cp)) in ("Mn", "Me", "Cf", "Lm", "Sk") or chr(cp) in "'.:^`·‘’․﹒＇．"),
    )
    return "".join(b)


def main() -> None:
    go = Path(sys.argv[1] if len(sys.argv) > 1 else "../fasthtmlparser")
    root = Path(__file__).resolve().parent.parent
    outputs = (
        (root / "include/fasthtmlparser/tag.hpp", tags(go)),
        (root / "include/fasthtmlparser/attr.hpp", attributes(go)),
        (root / "src/entities.inc", entities(go)),
        (root / "src/unicode_tables.inc", unicode_tables()),
    )
    for path, content in outputs:
        path.write_text(content, encoding="utf-8", newline="\n")
        print("wrote", path)


if __name__ == "__main__":
    main()
